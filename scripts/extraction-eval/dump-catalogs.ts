#!/usr/bin/env node
/**
 * Regenerate the catalogue snapshot the extraction eval scores against.
 *
 * The catalogue is the vocabulary the extract stage is prompted with and the table the
 * deterministic resolver matches against, so it has to be pinned. Fetching it live at eval time
 * would let an unrelated catalogue edit silently move every score.
 *
 * Reads the three reference tables and writes test/fixtures/extraction/shared/catalogs.json.
 * Reference data only — no patient data is read or written by this script.
 *
 *   SUPABASE_URL=... SUPABASE_ANON_KEY=... npx tsx scripts/extraction-eval/dump-catalogs.ts
 *
 * Ids are synthetic and assigned by position. Nothing in the corpus scores catalog_id,
 * finding_type_id or body_site_id, and committing real primary keys would pin the fixture to
 * whichever database it was dumped from.
 */
import { writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { REPO_ROOT, CATALOGS_PATH } from "./paths.ts";

type Row = Record<string, unknown>;

const TABLES = [
  {
    key: "observationCatalog",
    table: "observation_catalog",
    columns: "obs_code,name_ru,name_en,canonical_unit,synonyms_ru,synonyms_en,accepted_units",
    order: "obs_code",
    idPrefix: "obs",
  },
  {
    key: "findingTypeCatalog",
    table: "finding_type_catalog",
    columns: "finding_code,name_ru,name_en,synonyms_ru,synonyms_en",
    order: "finding_code",
    idPrefix: "ft",
  },
  {
    key: "bodySiteCatalog",
    table: "body_site_catalog",
    columns: "site_code,name_ru,name_en,parent_site_code,synonyms_ru,synonyms_en",
    order: "site_code",
    idPrefix: "bs",
  },
] as const;

async function fetchTable(
  baseUrl: string,
  apiKey: string,
  spec: (typeof TABLES)[number],
): Promise<Row[]> {
  const url = `${baseUrl.replace(/\/$/, "")}/rest/v1/${spec.table}?select=${spec.columns}&order=${spec.order}.asc`;
  const response = await fetch(url, {
    headers: { apikey: apiKey, Authorization: `Bearer ${apiKey}` },
  });
  if (!response.ok) {
    throw new Error(`${spec.table}: ${response.status} ${await response.text()}`);
  }
  const rows = (await response.json()) as Row[];
  if (rows.length === 0) {
    throw new Error(
      `${spec.table}: returned 0 rows. Reference tables are never empty, so this is almost ` +
        `certainly RLS hiding them from this key rather than a real result. Refusing to write ` +
        `an empty snapshot.`,
    );
  }
  return rows.map((row, index) => ({
    id: `${spec.idPrefix}-${String(index + 1).padStart(3, "0")}`,
    ...row,
    synonyms_ru: row.synonyms_ru ?? [],
    synonyms_en: row.synonyms_en ?? [],
    ...(spec.key === "observationCatalog" ? { accepted_units: row.accepted_units ?? {} } : {}),
  }));
}

export async function runCli(): Promise<void> {
  const baseUrl = process.env.SUPABASE_URL ?? process.env.NEXT_PUBLIC_SUPABASE_URL;
  const apiKey =
    process.env.SUPABASE_ANON_KEY ??
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ??
    process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!baseUrl || !apiKey) {
    throw new Error("Set SUPABASE_URL and SUPABASE_ANON_KEY (or SUPABASE_SERVICE_ROLE_KEY).");
  }

  const snapshot: Record<string, unknown> = {
    $comment:
      "Generated by scripts/extraction-eval/dump-catalogs.ts. Do not hand-edit — regenerate. " +
      "Ids are synthetic and positional; nothing in the corpus scores the *_id columns.",
  };
  for (const spec of TABLES) {
    const rows = await fetchTable(baseUrl, apiKey, spec);
    snapshot[spec.key] = rows;
    process.stdout.write(`[dump-catalogs] ${spec.table}: ${rows.length} rows\n`);
  }

  await mkdir(path.dirname(CATALOGS_PATH), { recursive: true });
  await writeFile(CATALOGS_PATH, `${JSON.stringify(snapshot, null, 2)}\n`, "utf8");
  process.stdout.write(`[dump-catalogs] wrote ${path.relative(REPO_ROOT, CATALOGS_PATH)}\n`);
}

const invokedScript = process.argv[1] ? new URL(`file://${process.argv[1]}`).href : "";
if (import.meta.url === invokedScript) {
  runCli().catch((error: unknown) => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
  });
}
