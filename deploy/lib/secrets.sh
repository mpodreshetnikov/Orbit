# shellcheck shell=bash
# Generated secrets for deploy/orbit. Sourced, never run.
#
# Every value here is created once, on the first install, and appended to deploy/.env under a
# marked section. Nothing is ever regenerated: a new JWT_SECRET would sign every user out and
# invalidate every connected MCP client, and a new POSTGRES_PASSWORD would lock the services out of
# a database initialised with the old one. To rotate one deliberately, see docs/SELF_HOSTING.md.
#
# A fresh install derives every value from one ORBIT_MASTER_KEY (HMAC-SHA256 over the value's
# name) instead of drawing it at random. A server rebuilt with the same master key then gets the
# same database password, API keys and backup encryption keys, so the one line is all that has to
# be kept somewhere safe. A value already in deploy/.env always wins over the derived one.

b64url() { openssl base64 -A | tr '+/' '-_' | tr -d '='; }
hex2bin() { printf '%b' "$(sed 's/../\\x&/g')"; }

# <bytes> random bytes as hex, or the first <bytes> of HMAC(master key, "orbit/<name>").
secret_hex() {
  local name="$1" bytes="$2"
  if [[ -n "${ORBIT_MASTER_KEY:-}" ]]; then
    printf 'orbit/%s' "$name" | openssl dgst -sha256 -hmac "$ORBIT_MASTER_KEY" -binary |
      head -c "$bytes" | od -An -tx1 | tr -d ' \n'
  else
    openssl rand -hex "$bytes"
  fi
}

# HS256 JWT in the shape Supabase's API keys have: {"role": ..., "iss": "supabase", iat, exp}.
# Issued "now" -- or, with a master key, at a fixed moment, so that the same key comes out again.
make_api_key() {
  local role="$1" secret="$2" now header payload signature
  now="$(date +%s)"
  [[ -z "${ORBIT_MASTER_KEY:-}" ]] || now=1767225600
  header="$(printf '{"alg":"HS256","typ":"JWT"}' | b64url)"
  payload="$(printf '{"role":"%s","iss":"supabase","iat":%s,"exp":%s}' "$role" "$now" $((now + 10 * 365 * 24 * 3600)) | b64url)"
  signature="$(printf '%s.%s' "$header" "$payload" | openssl dgst -sha256 -hmac "$secret" -binary | b64url)"
  printf '%s.%s.%s' "$header" "$payload" "$signature"
}

# Web Push (VAPID) key pair on P-256, both halves base64url as the web-push library expects:
# the public key is the uncompressed point (65 bytes), the private key the scalar (32 bytes).
make_vapid_keys() {
  local der
  der="$(mktemp)"
  # SEC1 DER of a P-256 key has a fixed layout: the 32-byte scalar starts at byte 7, and the
  # uncompressed public point is the last 65 bytes. A derived scalar goes in as a SEC1 key without
  # its public half, which openssl computes on the way out.
  if [[ -n "${ORBIT_MASTER_KEY:-}" ]]; then
    printf '30310201010420%sa00a06082a8648ce3d030107' "$(secret_hex VAPID_PRIVATE_KEY 32)" | hex2bin |
      openssl ec -inform DER -outform DER -out "$der" 2>/dev/null
  else
    openssl ecparam -name prime256v1 -genkey -noout 2>/dev/null | openssl ec -outform DER -out "$der" 2>/dev/null
  fi
  VAPID_PRIVATE_KEY_NEW="$(head -c 39 "$der" | tail -c 32 | b64url)"
  VAPID_PUBLIC_KEY_NEW="$(tail -c 65 "$der" | b64url)"
  rm -f "$der"
}

env_has() { grep -Eq "^$1=.+" "$2"; }

env_append() {
  local file="$1" name="$2" value="$3" tmp
  # A line the person left empty (ORBIT_MASTER_KEY= in .env.example) is filled where it stands.
  if grep -q "^$name=\$" "$file"; then
    tmp="$(mktemp)"
    awk -v n="$name" -v v="$value" '!done && $0 == n "=" { print n "=" v; done = 1; next } { print }' "$file" >"$tmp"
    cat "$tmp" >"$file"
    rm -f "$tmp"
    ok "generated $name"
    return
  fi
  if ! grep -q '^# ---- Generated by deploy/orbit' "$file"; then
    printf '\n# ---- Generated by deploy/orbit on %s. Do not edit, do not share, do not lose. ----\n' "$(date -u +%F)" >>"$file"
  fi
  printf '%s=%s\n' "$name" "$value" >>"$file"
  ok "generated $name"
}

# Sets <name> to <value> in deploy/.env: on the line that has it, or else just above the generated
# section. The file is read by bash and by docker compose, so a value with characters either would
# take for syntax is single-quoted, and one that cannot be quoted (a quote or a line break) refused.
env_set() {
  local file="$1" name="$2" value="$3" line tmp
  if [[ "$value" =~ ^[A-Za-z0-9_./:@,+=%~-]*$ ]]; then
    line="$name=$value"
  elif [[ "$value" != *"'"* && "$value" != *$'\n'* ]]; then
    line="$name='$value'"
  else
    die "$name: a value with a quote (') or a line break cannot go into deploy/.env"
  fi
  tmp="$(mktemp)"
  NAME="$name" LINE="$line" awk '
    index($0, ENVIRON["NAME"] "=") == 1 { if (!done) print ENVIRON["LINE"]; done = 1; next }
    /^# ---- Generated by deploy\/orbit/ && !done { print ENVIRON["LINE"]; done = 1 }
    { print }
    END { if (!done) print ENVIRON["LINE"] }
  ' "$file" >"$tmp"
  cat "$tmp" >"$file"
  rm -f "$tmp"
}

# Appends <name> with <bytes> of secret_hex unless deploy/.env already has a value for it.
ensure_hex() {
  local file="$1" name="$2" bytes="$3"
  env_has "$name" "$file" || env_append "$file" "$name" "$(secret_hex "$name" "$bytes")"
}

ensure_secrets() {
  local file="$1" jwt
  # A first install gets a master key to derive everything else from. An instance whose secrets
  # were drawn at random before master keys existed keeps them; there the whole file is the key.
  if [[ -z "${ORBIT_MASTER_KEY:-}" ]] && ! env_has POSTGRES_PASSWORD "$file"; then
    ORBIT_MASTER_KEY="$(openssl rand -hex 32)"
    env_append "$file" ORBIT_MASTER_KEY "$ORBIT_MASTER_KEY"
    # shellcheck disable=SC2034 # read by summary() in deploy/orbit
    ORBIT_MASTER_KEY_CREATED=1
  fi
  ensure_hex "$file" POSTGRES_PASSWORD 24
  ensure_hex "$file" JWT_SECRET 32
  jwt="$(grep -E '^JWT_SECRET=' "$file" | tail -1 | cut -d= -f2-)"
  env_has ANON_KEY "$file" || env_append "$file" ANON_KEY "$(make_api_key anon "$jwt")"
  env_has SERVICE_ROLE_KEY "$file" || env_append "$file" SERVICE_ROLE_KEY "$(make_api_key service_role "$jwt")"
  ensure_hex "$file" SECRET_KEY_BASE 32
  ensure_hex "$file" REALTIME_DB_ENC_KEY 8
  ensure_hex "$file" VAULT_ENC_KEY 16
  ensure_hex "$file" PG_META_CRYPTO_KEY 24
  ensure_hex "$file" S3_PROTOCOL_ACCESS_KEY_ID 16
  ensure_hex "$file" S3_PROTOCOL_ACCESS_KEY_SECRET 32
  ensure_hex "$file" DASHBOARD_PASSWORD 16
  ensure_hex "$file" MCP_OAUTH_SIGNING_SECRET 32
  ensure_hex "$file" MONEY_FX_SYNC_TOKEN 24
  # Encrypt both backup copies before they leave the server.
  ensure_hex "$file" BACKUP_ENCRYPTION_KEY 32
  ensure_hex "$file" BACKUP_SNAPSHOT_PASSWORD 32
  if ! env_has VAPID_PUBLIC_KEY "$file" || ! env_has VAPID_PRIVATE_KEY "$file"; then
    make_vapid_keys
    env_append "$file" VAPID_PUBLIC_KEY "$VAPID_PUBLIC_KEY_NEW"
    env_append "$file" VAPID_PRIVATE_KEY "$VAPID_PRIVATE_KEY_NEW"
  fi
  chmod 600 "$file"
}
