# shellcheck shell=bash
# Generated secrets for deploy/orbit. Sourced, never run.
#
# Every value here is created once, on the first install, and appended to deploy/.env under a
# marked section. Nothing is ever regenerated: a new JWT_SECRET would sign every user out and
# invalidate every connected MCP client, and a new POSTGRES_PASSWORD would lock the services out of
# a database initialised with the old one. To rotate one deliberately, see docs/SELF_HOSTING.md.

b64url() { openssl base64 -A | tr '+/' '-_' | tr -d '='; }

# HS256 JWT in the shape Supabase's API keys have: {"role": ..., "iss": "supabase", iat, exp}.
make_api_key() {
  local role="$1" secret="$2" now header payload signature
  now="$(date +%s)"
  header="$(printf '{"alg":"HS256","typ":"JWT"}' | b64url)"
  payload="$(printf '{"role":"%s","iss":"supabase","iat":%s,"exp":%s}' "$role" "$now" $((now + 10 * 365 * 24 * 3600)) | b64url)"
  signature="$(printf '%s.%s' "$header" "$payload" | openssl dgst -sha256 -hmac "$secret" -binary | b64url)"
  printf '%s.%s.%s' "$header" "$payload" "$signature"
}

# Web Push (VAPID) key pair on P-256, both halves base64url as the web-push library expects:
# the public key is the uncompressed point (65 bytes), the private key the scalar (32 bytes).
make_vapid_keys() {
  local der
  der="$(mktemp)"
  # SEC1 DER of a P-256 key has a fixed layout: the 32-byte scalar starts at byte 7, and the
  # uncompressed public point is the last 65 bytes.
  openssl ecparam -name prime256v1 -genkey -noout 2>/dev/null | openssl ec -outform DER -out "$der" 2>/dev/null
  VAPID_PRIVATE_KEY_NEW="$(head -c 39 "$der" | tail -c 32 | b64url)"
  VAPID_PUBLIC_KEY_NEW="$(tail -c 65 "$der" | b64url)"
  rm -f "$der"
}

env_has() { grep -Eq "^$1=.+" "$2"; }

env_append() {
  local file="$1" name="$2" value="$3"
  if ! grep -q '^# ---- Generated by deploy/orbit' "$file"; then
    printf '\n# ---- Generated by deploy/orbit on %s. Do not edit, do not share, do not lose. ----\n' "$(date -u +%F)" >>"$file"
  fi
  printf '%s=%s\n' "$name" "$value" >>"$file"
  ok "generated $name"
}

ensure_secrets() {
  local file="$1" jwt
  env_has POSTGRES_PASSWORD "$file" || env_append "$file" POSTGRES_PASSWORD "$(openssl rand -hex 24)"
  if ! env_has JWT_SECRET "$file"; then
    env_append "$file" JWT_SECRET "$(openssl rand -hex 32)"
  fi
  jwt="$(grep -E '^JWT_SECRET=' "$file" | tail -1 | cut -d= -f2-)"
  env_has ANON_KEY "$file" || env_append "$file" ANON_KEY "$(make_api_key anon "$jwt")"
  env_has SERVICE_ROLE_KEY "$file" || env_append "$file" SERVICE_ROLE_KEY "$(make_api_key service_role "$jwt")"
  env_has SECRET_KEY_BASE "$file" || env_append "$file" SECRET_KEY_BASE "$(openssl rand -hex 32)"
  env_has REALTIME_DB_ENC_KEY "$file" || env_append "$file" REALTIME_DB_ENC_KEY "$(openssl rand -hex 8)"
  env_has VAULT_ENC_KEY "$file" || env_append "$file" VAULT_ENC_KEY "$(openssl rand -hex 16)"
  env_has PG_META_CRYPTO_KEY "$file" || env_append "$file" PG_META_CRYPTO_KEY "$(openssl rand -hex 24)"
  env_has S3_PROTOCOL_ACCESS_KEY_ID "$file" || env_append "$file" S3_PROTOCOL_ACCESS_KEY_ID "$(openssl rand -hex 16)"
  env_has S3_PROTOCOL_ACCESS_KEY_SECRET "$file" || env_append "$file" S3_PROTOCOL_ACCESS_KEY_SECRET "$(openssl rand -hex 32)"
  env_has DASHBOARD_PASSWORD "$file" || env_append "$file" DASHBOARD_PASSWORD "$(openssl rand -hex 16)"
  env_has MCP_OAUTH_SIGNING_SECRET "$file" || env_append "$file" MCP_OAUTH_SIGNING_SECRET "$(openssl rand -hex 32)"
  env_has MONEY_FX_SYNC_TOKEN "$file" || env_append "$file" MONEY_FX_SYNC_TOKEN "$(openssl rand -hex 24)"
  # Encrypt both backup copies before they leave the server.
  env_has BACKUP_ENCRYPTION_KEY "$file" || env_append "$file" BACKUP_ENCRYPTION_KEY "$(openssl rand -hex 32)"
  env_has BACKUP_SNAPSHOT_PASSWORD "$file" || env_append "$file" BACKUP_SNAPSHOT_PASSWORD "$(openssl rand -hex 32)"
  if ! env_has VAPID_PUBLIC_KEY "$file" || ! env_has VAPID_PRIVATE_KEY "$file"; then
    make_vapid_keys
    env_append "$file" VAPID_PUBLIC_KEY "$VAPID_PUBLIC_KEY_NEW"
    env_append "$file" VAPID_PRIVATE_KEY "$VAPID_PRIVATE_KEY_NEW"
  fi
  chmod 600 "$file"
}
