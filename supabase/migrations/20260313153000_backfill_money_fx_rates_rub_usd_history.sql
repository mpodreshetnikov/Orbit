INSERT INTO public.money_fx_rates (
  rate_date,
  base_currency,
  quote_currency,
  rate
)
SELECT
  daily.rate_date,
  'USD'::char(3),
  'RUB'::char(3),
  daily.usd_rub_rate
FROM daily_rates AS daily
UNION ALL
SELECT
  daily.rate_date,
  'RUB'::char(3),
  'USD'::char(3),
  round((1 / daily.usd_rub_rate)::numeric, 12)
FROM daily_rates AS daily
ON CONFLICT (rate_date, base_currency, quote_currency) DO UPDATE
SET rate = EXCLUDED.rate;

