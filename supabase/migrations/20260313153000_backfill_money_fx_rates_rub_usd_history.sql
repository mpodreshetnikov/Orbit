  SELECT
    series.rate_date::date AS rate_date,
    (
      SELECT official.usd_rub_rate
      FROM official_rates AS official
      WHERE official.rate_date <= series.rate_date::date
      ORDER BY official.rate_date DESC
      LIMIT 1
