-- 2. Conversions for units labs print that the entry neither keeps nor converts from.
--
-- Without one, a known unit that differs from the canonical one is refused for the entry's history
-- (`unitFitsEntry`): MCHC printed in g/dL, or LH in IU/L, never reached the chart. Factors:
-- protein and albumin g/dL x10; bilirubin mg/dL x17.1; fibrinogen mg/dL x0.01; CRP mg/dL x10;
-- VLDL mg/dL x0.0259; free T4 ng/dL x12.87; testosterone ng/mL x3.467 and ng/dL x0.03467; free
-- testosterone pmol/L / 3.467; folate nmol/L / 2.266; hematocrit L/L x100. The rest are the same
-- quantity under another name: PSA ug/L, LH and FSH IU/L, TSH uIU/mL, RF U/mL, electrolytes
-- mEq/L, cell counts 10^3/uL and 10^6/uL.
